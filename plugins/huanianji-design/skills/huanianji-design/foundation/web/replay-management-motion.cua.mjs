export async function replayManagementMotion({tab,fs,root,phase}) {
  const {createHash}=await import('node:crypto');
  const probe=await fs.readFile(root+'/web/observe-management.js','utf8');
  const manifest=JSON.parse(await fs.readFile(root+'/generated/manifest.json','utf8'));
  const bundle=JSON.parse(await fs.readFile(root+'/'+manifest.bundle+'/profiles.json','utf8'));
  const expandMs=bundle.profiles.management.web.motion.expand_seconds*1000;
  const checks=[];
  const check=(name,passed,detail)=>checks.push({name,passed,detail});
  const observe=()=>tab.playwright.evaluate('('+probe+')()');
  const click=id=>tab.playwright.locator('#'+id).click();
  const person=id=>tab.playwright.locator('[data-person="'+id+'"] .roster-select').click();
  await tab.reload();await tab.getAXState({emit:false});
  const start=Date.now();
  await person('xiaocheng');
  await tab.playwright.locator('#query').fill('绘画');
  const filtered=await observe();
  check('filter_cancels_previous_detail_motion',filtered.observed.selected==='yuehe'&&filtered.observed.detail_settled,{elapsed_ms:Date.now()-start,...filtered.observed});
  await tab.getAXState({emit:false});
  await tab.playwright.locator('#query').fill('');
  await person('linxi');
  await click('task-2');
  await person('xiaocheng');
  await tab.getAXState({emit:false});
  await tab.playwright.locator('#detail-content[style*="transform: none"]').waitFor({state:'visible'});
  const glyph=await tab.playwright.evaluate(()=>({checked:document.getElementById('task-2').checked,offset:getComputedStyle(document.querySelector('#task-2+.check-art path')).strokeDashoffset.replace('px','')*1}));
  check('check_motion_belongs_to_current_person',!glyph.checked&&glyph.offset===1,glyph);
  const openingStart=Date.now();await click('note-toggle');
  const opening=await observe(),openingElapsed=Date.now()-openingStart;
  check('arrow_moves_with_disclosure',openingElapsed<expandMs&&opening.observed.raw.arrow_transform!=='none'&&!opening.observed.raw.arrow_transform.startsWith('matrix(-1,'),{elapsed_ms:openingElapsed,...opening.observed.raw});
  await tab.getAXState({emit:false});
  const reverseStart=Date.now();await click('note-toggle');
  const reverse=await observe(),reverseElapsed=Date.now()-reverseStart;
  check('reverse_keeps_intermediate_angle',reverseElapsed<expandMs&&reverse.observed.raw.arrow_transform!=='none'&&!reverse.observed.raw.arrow_transform.startsWith('matrix(-1,'),{elapsed_ms:reverseElapsed,...reverse.observed.raw});
  await tab.getAXState({emit:false});
  await click('mode');await tab.getAXState({emit:false});
  await tab.playwright.locator('#note-region[style*="height: 0px"]').waitFor({state:'attached'});
  const themed=await observe();
  check('theme_during_collapse_preserves_target',themed.theme==='dark'&&!themed.observed.note_open&&themed.observed.raw.arrow_transform==='none',themed.observed);
  await click('note-toggle');await click('reduce');await tab.getAXState({emit:false});
  const reduced=await observe();
  check('reduce_during_disclosure_settles',reduced.reduced&&reduced.observed.note_open&&reduced.observed.raw.arrow_transform.startsWith('matrix(-1,'),reduced.observed);
  const file='evidence/management-motion-'+phase+'-web.jpg';
  await fs.writeFile(root+'/'+file,await tab.getScreenshot({emit:false}));
  const result={build_id:manifest.build_id,implementation_sha256:createHash('sha256').update(await fs.readFile(root+'/web/fragments.js')).digest('hex'),input_driver:'CUA click/fill',checks,failed:checks.filter(c=>!c.passed),screenshot:file};
  await fs.writeFile(root+'/evidence/management-motion-'+phase+'-web.json',JSON.stringify(result,null,2)+'\n');
  return {checks:checks.length,failed:result.failed.map(c=>c.name)};
}
